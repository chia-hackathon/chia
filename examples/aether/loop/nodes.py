"""Build / run / score nodes for the kernel-optimization loop.

One iteration is: agent's kernel bytes -> ELF (riscv_build) -> simulator run
(verilator_run) -> Measurement. The simulator itself is built once by
``build_simulator`` and reused by value across every iteration.

Nothing here hard-codes a benchmark: the selected `Kernel` entry supplies the
editable file, the ELF name and the regexes that read the objective out of the
simulator log. Every Ray remote takes those as explicit arguments, so remote
workers never need the driver's selection.

Two targets, one pipeline. Saturn benchmarks are assembled from the local
`BENCHMARKS_DIR` checkout by `collateral.py`. Gemmini ones cannot be: their
`gemmini_params.h` is *generated by Chisel elaboration*, so the tree is a
function of the hardware config and has to be fetched off the chipyard
container — that is what `gemmini_params_rebuild` / `gemmini_collateral` do.
`build_kernel` dispatches between the two on `K().target`.

INTEGRATION NOTE for `loop.py`: it still imports `pristine_kernel` and
`build_inputs` from `collateral`, which only know about `BENCHMARKS_DIR` and
therefore raise for a Gemmini entry. Swap those two call sites for
`nodes.pristine_kernel_for()` / `nodes.build_inputs_for(kernel)` (defined at
the bottom of this file, same signatures) and the loop runs either target
unchanged.

A rule the Gemmini remote has to obey and the others do not: it must not
reference a module global of `nodes` or `constants`. Ray ships this directory
as the single importable package `loop`, so a by-reference pickle of anything
named `nodes.X` / `constants.X` dies on the worker with `ModuleNotFoundError`.
Hence its defaults-by-value signature and its plain-dict return.
"""

