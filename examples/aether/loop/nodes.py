@dataclass
class Measurement:
    """Outcome of one build+run attempt."""
    ok: bool               # compiled, ran, and the benchmark self-check passed
    kind: str              # "ok" | "build_failure" | "sim_failure" | "incorrect"
    cycles: int | None     # cycles around the kernel (the objective; lower is better)
    instret: int | None
    detail: str


# ---------------------------------------------------------------------------
# Simulator (built once — the hardware is fixed for this loop)
# ---------------------------------------------------------------------------

def build_simulator() -> BuildArtifact:
    """Elaborate + verilate the selected config. ~72s cold on this image."""
    config = CONFIG()
    node = ChiselBuildNode(
        chipyard_path=CHIPYARD_PATH,
        config=config,
        config_package=CONFIG_PACKAGE,
        target=BuildTarget.VERILATOR,
        timeout_seconds=CHISEL_BUILD_TIMEOUT_SECONDS,
    )
    logger.info("Building simulator %s", config)
    art = get(node.build.options(
        resources={"chipyard": CHISEL_BUILD_RESOURCE}).chia_remote(node))
    if not art.success:
        raise RuntimeError(f"simulator build failed (rc={art.returncode})\n"
                           f"{art.stderr[-3000:]}")
    return art


# ---------------------------------------------------------------------------
# Kernel -> ELF
# ---------------------------------------------------------------------------

def _compile_command() -> str:
    """Mirror saturn/benchmarks/Makefile's compile_template for this bench."""
    k = K()
    srcs = [f"{k.bench_dir}/*.c", f"{k.bench_dir}/*.S",
            "common/*.c", "common/*.S", "common/ara/*.c"]
    parts = [CC, *cflags(k.bench_dir), "-o", k.elf_name, *srcs, *LDFLAGS]
    # shell string (not a list) so the globs expand on the build container
    return " ".join(shlex.quote(p) if "*" not in p else p for p in parts)


def build_kernel(kernel: bytes):
    """Compile *kernel* against the sealed collateral; return ProgramBuildArtifact.

    Dispatches on the selected entry's ``target``: Saturn benchmarks are
    assembled from the local ``BENCHMARKS_DIR`` checkout (``collateral.py``),
    Gemmini ones from the hardware-derived tree that
    :func:`gemmini_collateral` fetched off the chipyard container.
    """
    if K().target == "gemmini":
        inputs, command = gemmini_build_inputs(kernel), gemmini_compile_command()
    else:
        inputs, command = build_inputs(kernel), _compile_command()
    node = RiscvBuildNode(timeout_seconds=BUILD_TIMEOUT_SECONDS)
    return get(node.build_program.options(
        resources={"riscv_build": RISCV_BUILD_RESOURCE}).chia_remote(
            node,
            input_files=inputs,
            command=command,
            work_dir=BUILD_WORK_DIR,
            outputs=[K().elf_name],
        ))


# ---------------------------------------------------------------------------
# ELF -> simulator run
# ---------------------------------------------------------------------------

def run_kernel(sim: BuildArtifact, elf: bytes) -> RunResult:
    node = VerilatorRunNode()
    return get(node.run.options(
        resources={"verilator_run": VERILATOR_RUN_RESOURCE}).chia_remote(
            node,
            artifact=sim,
            test_binary_content=elf,
            test_binary_name=K().elf_name,
            work_dir="/tmp/aether-sim",
            timeout_cycles=K().sim_timeout_cycles or SIM_TIMEOUT_CYCLES,
            timeout_seconds=K().sim_timeout_seconds or SIM_TIMEOUT_SECONDS,
            verbose=False,
        ))


def _extract(pattern: str | None, log: str, agg: str) -> int | None:
    """Pull the objective (or minstret) out of the simulator log."""
    if not pattern:
        return None
    vals = [int(m) for m in re.findall(pattern, log)]
    if not vals:
        return None
    if agg == "sum":
        return sum(vals)
    if agg == "last":
        return vals[-1]
    return vals[0]


def measure(build, run: RunResult | None) -> Measurement:
    """Classify one attempt. The self-check inside the benchmark decides
    correctness; we only read the numbers it prints."""
    k = K()
    if build is None or not build.success:
        tail = (build.stderr or build.stdout or "")[-2000:] if build else "no build"
        return Measurement(False, "build_failure", None, None, tail)
    if run is None:
        return Measurement(False, "sim_failure", None, None, "simulator did not run")

    log = f"{run.log or ''}\n{run.out or ''}"
    cycles = _extract(k.cycle_re, log, k.metric_agg)
    instret = _extract(k.instret_re, log, k.metric_agg)

    if not run.success:
        return Measurement(False, "incorrect", cycles, instret,
                           f"simulator rc={run.returncode}; "
                           f"the benchmark's self-check did not pass")
    if cycles is None:
        return Measurement(False, "sim_failure", None, None,
                           f"ran but printed nothing matching {k.cycle_re!r} — "
                           "did the harness change?")
    return Measurement(True, "ok", cycles, instret,
                       f"passed, cycles={cycles}, instret={instret}")


